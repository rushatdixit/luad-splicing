"""Phase 2: QC report. Run from the repo root after build_matrix and splits:  python -m src.qc_report

Purely descriptive: nothing here filters, excludes or imputes anything. Writes docs/qc_report.md
(generated; edit this script, not the doc) and results/tables/qc_*.csv.
"""
import importlib
import platform
from datetime import date

import numpy as np
import pandas as pd

from src.build_inventory import md_table
from src.build_matrix import load_features, load_metadata
from src.splits import N_FOLDS, N_REPEATS, SEED

TABLES, DOC = "results/tables", "docs/qc_report.md"
HIGH_MISSING = 0.20  # flag-only threshold for per-sample missingness


def counts(sub):
    """Sample/patient composition of one subset of the split table."""
    return {"patients": sub["patient_id"].nunique(), "samples": len(sub),
            "tumour": int((sub.label == 1).sum()), "normal": int((sub.label == 0).sum()),
            "pairs": int((sub.is_paired & (sub.label == 0)).sum()),
            "sites": sub["site"].nunique(),
            "samples_7site": int(sub.normal_site.sum()),
            "normal_7site": int((sub.normal_site & (sub.label == 0)).sum())}


def main():
    X, meta = load_features(), load_metadata()
    s = pd.read_csv("data/processed/splits.csv", dtype={"site": str})
    assert list(X.index) == list(meta.sample_id) == list(s.sample_id), "row order differs between files"

    # ---- matrix QC ----------------------------------------------------------------------------
    n_nan = int(X.isna().sum().sum())
    smp_miss = X.isna().mean(axis=1).rename("frac_missing")
    high = meta.set_index("sample_id").join(smp_miss)
    high = high[high.frac_missing > HIGH_MISSING].sort_values("frac_missing", ascending=False)
    dup_samples = X[X.duplicated(keep=False)]
    n_constant = int((X.nunique(dropna=True) <= 1).sum())
    n_all_nan_sample = int(X.isna().all(axis=1).sum())

    # ---- split QC -----------------------------------------------------------------------------
    sets = pd.DataFrame({k: counts(g) for k, g in [("all", s), *s.groupby("set")]}).T
    folds = []
    for r in range(N_REPEATS):
        for f in range(N_FOLDS):
            v = s[s[f"cv_rep{r}"] == f]
            folds.append({"repeat": r, "fold": f, "role": "validation", **counts(v)})
            folds.append({"repeat": r, "fold": f, "role": "training",
                          **counts(s[(s.set == "train") & (s[f"cv_rep{r}"] != f)])})
    folds = pd.DataFrame(folds)
    fold_summary = (folds.groupby("role").agg(["min", "median", "max"])
                    .drop(columns=["repeat", "fold"], level=0))
    fold_summary.columns = [f"{a}_{b}" for a, b in fold_summary.columns]
    tp = s[s.set == "test"].drop_duplicates("patient_id")
    test_sites = s[s.set == "test"].groupby("site").agg(
        tumour=("label", "sum"), normal=("label", lambda x: int((x == 0).sum())))

    sets.to_csv(f"{TABLES}/qc_split_sets.csv")
    folds.to_csv(f"{TABLES}/qc_split_folds.csv", index=False)
    fold_summary.to_csv(f"{TABLES}/qc_split_summary.csv")
    high[["sample_type", "site", "frac_missing"]].to_csv(f"{TABLES}/qc_high_missing_samples.csv")

    versions = {"python": platform.python_version()}
    for m in ["pandas", "numpy", "scipy", "sklearn", "statsmodels", "matplotlib", "seaborn"]:
        versions[m] = importlib.import_module(m).__version__

    # Compact fold table: one row per metric, min-median-max across the 50 validation folds.
    val = fold_summary.loc["validation"]
    fold_tbl = pd.DataFrame({m: [f"{val[m + '_min']:g} / {val[m + '_median']:g} / {val[m + '_max']:g}"]
                             for m in counts(s)}).T.rename(columns={0: "validation fold: min / median / max"})
    trn = fold_summary.loc["training"]
    fold_tbl["CV training part: min / median / max"] = [f"{trn[m + '_min']:g} / {trn[m + '_median']:g} / {trn[m + '_max']:g}"
                                                        for m in counts(s)]

    doc = f"""# QC report: analysis-ready matrix and splits

> **Generated by `src/qc_report.py`. Do not edit by hand.** Generated on {date.today().isoformat()}.
> Rebuild: `python -m src.build_matrix && python -m src.splits && python -m src.qc_report` (env `luad-splicing`).

## 1. Analysis-ready table

| Item | Value |
|---|---|
| Feature table | `data/processed/psi_samples_x_events.csv.gz`: {X.shape[0]} samples (rows) × {X.shape[1]:,} events (columns), PSI only |
| Metadata (separate file) | `data/processed/sample_metadata.csv`: sample_id, patient_id, site, label, sample_type, is_paired, normal_site |
| Events removed | **0**. No coverage, variance, label-aware or whole-dataset filtering was applied (all such steps are deferred to inside training folds) |
| Imputation / scaling | none applied |
| Missing cells | {n_nan:,} of {X.size:,} ({n_nan / X.size:.2%}), kept as NaN |
| Value range | {np.nanmin(X.values)} to {np.nanmax(X.values)} |
| Row alignment | feature rows, metadata rows and split rows are in identical order (asserted) |
| Feature columns | event IDs (`as_id`) only; no label, patient, site or clinical column (asserted in `build_matrix.py`) |

Descriptive checks (nothing was removed because of them):
- Samples with every event missing: {n_all_nan_sample}.
- Exact-duplicate sample vectors: {len(dup_samples)}{" (" + ", ".join(dup_samples.index) + ")" if len(dup_samples) else ""}.
- Events constant across all non-missing samples: {n_constant}. Not removed; any variance filter is fitted inside training folds.
- Samples with > {HIGH_MISSING:.0%} of events missing (**flagged only, kept**): {len(high)}.

{md_table(high[["sample_type", "site", "frac_missing"]], index=True) if len(high) else ""}

## 2. Splits (`data/processed/splits.csv`, seed {SEED})

Patient-level, stratified by pair status and site group. Generated from metadata only, before any EDA. Design: `docs/analysis_plan.md` §B.

### Held-out test vs training

{md_table(sets, index=True)}

- **Patients in both train and test: 0** (asserted in `src/splits.py` and `tests/test_phase2.py`).
- The test set has {int(sets.loc['test', 'normal'])} normals ({int(sets.loc['test', 'pairs'])} of them paired), from {len(test_sites)} sites.
  With so few normals, the final test ROC-AUC will have a wide confidence interval. This is a known limitation of the cohort, not of the split.
- Test samples per site: {", ".join(f"{i} ({r.tumour}T/{r.normal}N)" for i, r in test_sites.iterrows())}.

### Repeated CV ({N_REPEATS} repeats × {N_FOLDS} folds on training patients)

Each row gives min / median / max across all {N_REPEATS * N_FOLDS} folds. "7site" means samples from the 7 normal-contributing sites.

{md_table(fold_tbl, index=True)}

Every validation fold contains normals and matched pairs, both overall and within the 7-site subset (asserted).
Full per-fold table: `results/tables/qc_split_folds.csv`.

## 3. Environment

Conda env `luad-splicing` (`environment.yml`): {", ".join(f"{k} {v}" for k, v in versions.items())}. Seed {SEED}.
"""
    with open(DOC, "w") as fh:
        fh.write(doc)
    print(f"wrote {DOC}")
    print(sets.to_string())
    print(fold_tbl.to_string())
    print(f"high-missing samples: {len(high)}; duplicates: {len(dup_samples)}; constant events: {n_constant}")


if __name__ == "__main__":
    main()
